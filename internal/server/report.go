package server

import (
	"fmt"
	"strings"
	"time"

	"github.com/KING-CYBERTON/project-pulse/internal/analytics"
)

var ragIcon = map[string]string{"green": "🟢", "amber": "🟠", "red": "🔴"}

func pct(p *float64) string {
	if p == nil {
		return "–"
	}
	return fmt.Sprintf("%.0f%%", *p*100)
}

func esc(s string) string {
	return strings.NewReplacer("|", "\\|", "\n", " ").Replace(s)
}

// Markdown renders a status report a PM can paste into a chat or email.
func Markdown(snap *Snapshot, days int) string {
	p := snap.Portfolio
	var b strings.Builder
	t := p.Totals
	fmt.Fprintf(&b, "# Project status – %s\n\n", snap.At.Format("Mon 2 Jan 2006"))
	fmt.Fprintf(&b, "%d projects: %d green, %d amber, %d red. %d commits and %d merged PRs in the last 30 days; %d open PRs (%d stale), %d open issues (%d bugs).\n\n",
		t.Projects, t.Green, t.Amber, t.Red, t.Commits30d, t.Merged30d, t.OpenPRs, t.StalePRs, t.OpenIssues, t.OpenBugs)

	b.WriteString("| Project | Health | Status | Commits 7d / 30d | Open PRs | Open issues | CI | Next milestone |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|\n")
	for _, s := range p.Projects {
		ms := "–"
		if s.Milestone != nil {
			ms = fmt.Sprintf("%s (%.0f%%)", esc(s.Milestone.Title), s.Milestone.Percent)
		}
		fmt.Fprintf(&b, "| [%s](%s) | %s %d (%s) | %s | %d / %d | %d | %d | %s %s | %s |\n",
			esc(s.Name), s.URL, ragIcon[s.RAG], s.Score, s.Grade, esc(s.StateLabel), s.Commits7d, s.Commits30d,
			s.OpenPRs, s.OpenIssues, s.CIStatus, pct(s.CISuccess), ms)
	}

	if len(p.Attention) > 0 {
		b.WriteString("\n## Needs attention\n\n")
		n := 0
		for _, k := range p.Attention {
			if k.Severity == "low" || n >= 12 {
				continue
			}
			n++
			fmt.Fprintf(&b, "- **%s** [%s] %s: %s\n", k.Project, k.Severity, k.Title, k.Detail)
		}
		if n == 0 {
			b.WriteString("- Nothing high or medium severity.\n")
		}
	}

	cut := snap.At.AddDate(0, 0, -days)
	for _, r := range snap.Reports {
		fmt.Fprintf(&b, "\n## %s %s\n\n", ragIcon[r.Health.RAG], r.Name)
		if r.Error != "" {
			fmt.Fprintf(&b, "Couldn't load: %s\n", r.Error)
			continue
		}
		if r.Description != "" {
			fmt.Fprintf(&b, "_%s_\n\n", esc(r.Description))
		}
		fmt.Fprintf(&b, "- **Status:** %s", r.Status.Label)
		if r.Status.LastCommitAt != nil {
			fmt.Fprintf(&b, " (last commit %s by %s: \"%s\")", r.Status.LastCommitAt.Format("2 Jan"), r.Status.LastCommitBy, r.Status.LastCommitTitle)
		}
		b.WriteString("\n")
		fmt.Fprintf(&b, "- **Velocity:** %d commits this week, %d in 30 days, trend %s", r.Activity.Commits7d, r.Activity.Commits30d, r.Activity.Trend)
		if r.Activity.TrendPct != nil {
			fmt.Fprintf(&b, " (%+d%%)", *r.Activity.TrendPct)
		}
		b.WriteString("\n")
		if r.Kind != "profile" {
			fmt.Fprintf(&b, "- **Delivery:** %d PRs merged in 30 days", r.Pulls.Merged30d)
			if r.Pulls.MedianMergeHours != nil {
				fmt.Fprintf(&b, ", median %.0fh to merge", *r.Pulls.MedianMergeHours)
			}
			fmt.Fprintf(&b, "; CI %s on %s (%s of runs pass)", r.CI.DefaultStatus, r.Branch, pct(r.CI.SuccessRate))
			if r.Releases.LatestTag != "" {
				fmt.Fprintf(&b, "; latest release %s", r.Releases.LatestTag)
			}
			b.WriteString("\n")
			if c := r.Progress.Current; c != nil {
				fmt.Fprintf(&b, "- **Milestone:** %s is %.0f%% done (%d open / %d closed)", c.Title, c.Percent, c.Open, c.Closed)
				if c.DueOn != nil {
					fmt.Fprintf(&b, ", due %s", c.DueOn.Format("2 Jan"))
				}
				b.WriteString("\n")
			}
		}
		shipped := []string{}
		for _, m := range r.Pulls.RecentMerged {
			if m.At != nil && m.At.After(cut) {
				shipped = append(shipped, fmt.Sprintf("  - #%d %s", m.Number, esc(m.Title)))
			}
		}
		if len(shipped) > 0 {
			fmt.Fprintf(&b, "- **Shipped in the last %d days:**\n%s\n", days, strings.Join(shipped, "\n"))
		}
		top := []analytics.Risk{}
		for _, k := range r.Risks {
			if k.Severity != "low" {
				top = append(top, k)
			}
		}
		if len(top) > 0 {
			b.WriteString("- **Risks:**\n")
			for _, k := range top {
				fmt.Fprintf(&b, "  - [%s] %s\n", k.Severity, k.Title)
			}
		}
	}
	fmt.Fprintf(&b, "\n---\nGenerated by Project Pulse at %s UTC from GitHub data (last %d days).\n", snap.At.Format(time.DateTime), p.Lookback)
	return b.String()
}
